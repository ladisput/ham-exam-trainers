#!/usr/bin/env python3
"""Build the public web app (installable, works offline, progress saved on each device).

Usage (run from the repo root):
  python3 tools/web.py build    write web/ from the exam sites, after `tools/site.py build <exam>` for each exam

web/ is what the host (Cloudflare Pages) serves, so commit it with every change. Never hand-edit it.
  web/index.html              the hub: one card per trainer
  web/fonts/                  Barlow and Barlow Condensed (OFL), shared by every trainer
  web/<exam>/                 one trainer: the exam's site files, plus manifest, service worker and icons.
                              Each trainer installs as its own app (its own home screen icon and offline copy).
To add an exam to the website, add it to WEB_EXAMS. Its exam.json needs "short" (the name under the home screen icon).

The artifact build (tools/site.py) is unchanged: both builds share app/template.html. The web build fills the
template's <!--fonts-->, <!--web-head--> and <!--web-body--> markers and sets CFG.web, which shows the
"Put it on your home screen" card. Progress lives in localStorage under the exam's "ls" key (never change it).
"""
import hashlib, json, os, shutil, sys

import importlib.util
_spec = importlib.util.spec_from_file_location("sitebuild", os.path.join(os.path.dirname(os.path.abspath(__file__)), "site.py"))
sitebuild = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(sitebuild)  # tools/site.py (not Python's own "site")

ROOT = sitebuild.ROOT
WEB = os.path.join(ROOT, "web")
SRC = os.path.join(ROOT, "app", "web")
WEB_EXAMS = ["technician"]  # add "general" and "extra" here when their sites are ready for the public
BG, INK, FACE, RED = "#e6e9e1", "#151918", "#f3f0e4", "#c4301c"

FONTS = [("Barlow", 400, "barlow-latin-400-normal"), ("Barlow", 500, "barlow-latin-500-normal"),
         ("Barlow", 600, "barlow-latin-600-normal"), ("Barlow Condensed", 500, "barlow-condensed-latin-500-normal"),
         ("Barlow Condensed", 600, "barlow-condensed-latin-600-normal"), ("Barlow Condensed", 700, "barlow-condensed-latin-700-normal")]


def icon(letter, size, path):
    """Home screen icon: the trainer's S-meter (cream arc, red needle past the pass line) over the exam letter.
    Everything sits inside the middle 80% circle, so the same picture is safe as a maskable icon."""
    from PIL import Image, ImageDraw, ImageFont
    import math
    S = 1024
    im = Image.new("RGB", (S, S), INK)
    d = ImageDraw.Draw(im)
    cx, cy, r = S / 2, 520, 300
    box = [cx - r, cy - r, cx + r, cy + r]
    d.arc(box, 205, 335, fill=FACE, width=34)
    d.arc(box, 300, 335, fill=RED, width=34)  # the band past the pass line
    for k in range(7):
        a = math.radians(205 + k * 130 / 6)
        d.line([(cx + (r - 70) * math.cos(a), cy + (r - 70) * math.sin(a)), (cx + (r - 30) * math.cos(a), cy + (r - 30) * math.sin(a))], fill=FACE, width=14)
    a = math.radians(312)
    d.line([(cx, cy), (cx + (r + 10) * math.cos(a), cy + (r + 10) * math.sin(a))], fill=RED, width=22)
    d.ellipse([cx - 30, cy - 30, cx + 30, cy + 30], fill=RED)
    f = ImageFont.truetype(os.path.join(SRC, "BarlowCondensed-Bold.ttf"), 380)
    d.text((cx, 745), letter, font=f, fill=FACE, anchor="mm")
    im.resize((size, size), Image.LANCZOS).save(path, optimize=True)


def head(exam_cfg):
    return f"""<link rel="manifest" href="manifest.webmanifest">
<meta name="theme-color" content="{BG}" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#111413" media="(prefers-color-scheme: dark)">
<meta name="description" content="{exam_cfg['heading'].capitalize()}: practice runs, mock exams and study pages for the US amateur radio exam. Works offline.">
<link rel="icon" href="icon-192.png" type="image/png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="{exam_cfg['short']}">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<script>addEventListener('beforeinstallprompt',e=>{{e.preventDefault();window.__bip=e;dispatchEvent(new Event('bip'))}});addEventListener('appinstalled',()=>{{window.__bip=null;dispatchEvent(new Event('bip'))}});</script>"""


BODY = """<script>
if('serviceWorker' in navigator)addEventListener('load',()=>navigator.serviceWorker.register('sw.js').catch(()=>{}));
if(navigator.storage&&navigator.storage.persist)navigator.storage.persist().catch(()=>{});
</script>"""

SW = """/* Offline copy of this trainer. Generated by tools/web.py; VERSION changes whenever any file changes. */
const VERSION = %(version)s;
const CACHE = 'trainer-' + VERSION;
const FILES = %(files)s;
const SCOPE_ID = %(scope)s;
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('trainer-') && k !== CACHE && k.endsWith('@' + SCOPE_ID)).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // Cached copy first (instant, and works with no signal); the network only for anything not in the copy.
  e.respondWith(caches.open(CACHE).then(async c => {
    const hit = await c.match(req, {ignoreSearch: true}) || (req.mode === 'navigate' ? await c.match('./') : null);
    return hit || fetch(req);
  }));
});
"""


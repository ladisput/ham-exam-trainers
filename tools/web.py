def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def build():
    if os.path.isdir(WEB):
        shutil.rmtree(WEB)
    # shared fonts
    os.makedirs(os.path.join(WEB, "fonts"))
    css = []
    for fam, w, f in FONTS:
        shutil.copy(os.path.join(SRC, "fonts", f + ".woff2"), os.path.join(WEB, "fonts", f + ".woff2"))
        css.append(f"@font-face{{font-family:'{fam}';font-style:normal;font-weight:{w};font-display:swap;src:url({f}.woff2) format('woff2')}}")
    shutil.copy(os.path.join(SRC, "fonts", "OFL.txt"), os.path.join(WEB, "fonts", "OFL.txt"))
    write(os.path.join(WEB, "fonts", "fonts.css"), "\n".join(css) + "\n")
    cards = []
    for exam in WEB_EXAMS:
        cfg = sitebuild.load(os.path.join(ROOT, "exams", exam, "exam.json"))
        if "short" not in cfg:
            sys.exit(f"exams/{exam}/exam.json needs \"short\" (the name under the home screen icon)")
        site, out = os.path.join(ROOT, "exams", exam, "site"), os.path.join(WEB, exam)
        shutil.copytree(site, out, ignore=shutil.ignore_patterns("index.html"))
        html = sitebuild.render(exam, {"web": True})
        a, b = html.index("<!--fonts-->"), html.index("<!--/fonts-->") + len("<!--/fonts-->")
        html = html[:a] + '<link rel="stylesheet" href="../fonts/fonts.css">' + html[b:]
        html = html.replace("<!--web-head-->", head(cfg)).replace("<!--web-body-->", BODY)
        write(os.path.join(out, "index.html"), html)
        icon(cfg["letter"], 192, os.path.join(out, "icon-192.png"))
        icon(cfg["letter"], 512, os.path.join(out, "icon-512.png"))
        icon(cfg["letter"], 180, os.path.join(out, "apple-touch-icon.png"))
        manifest = {"name": cfg["title"], "short_name": cfg["short"], "id": "./", "start_url": "./", "scope": "./",
                    "display": "standalone", "background_color": BG, "theme_color": BG,
                    "description": f"Practice runs, mock exams and study pages for the {cfg['heading'].split(' ')[0]} exam. Works offline.",
                    "icons": [{"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
                              {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
                              {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
        write(os.path.join(out, "manifest.webmanifest"), json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
        # offline copy: every file of this trainer plus the shared fonts
        files, h = ["./"], hashlib.sha256()
        for d, _, fs in sorted(os.walk(out)):
            for f in sorted(fs):
                rel = os.path.relpath(os.path.join(d, f), out).replace(os.sep, "/")
                files.append(rel)
                h.update(rel.encode()); h.update(open(os.path.join(d, f), "rb").read())
        for _, _, f in FONTS:
            files.append(f"../fonts/{f}.woff2")
            h.update(open(os.path.join(WEB, "fonts", f + ".woff2"), "rb").read())
        files.append("../fonts/fonts.css"); h.update(css[0].encode())
        version = h.hexdigest()[:12]
        write(os.path.join(out, "sw.js"), SW % {"version": json.dumps(version + "@" + exam), "files": json.dumps(files, indent=0),
                                                "scope": json.dumps(exam)})
        n = len(sitebuild.load(os.path.join(site, "pool.json"))["qs"])
        cards.append(f'<a class="card" href="{exam}/"><img src="{exam}/icon-192.png" alt=""><div><h2>{cfg["heading"].capitalize()}</h2>'
                     f'<p class="small mute">{cfg["element"]} · {n} questions · {cfg["ex"]} on the exam, {cfg["pass"]} to pass</p></div><span class="go">Open</span></a>')
        print(f"Built web/{exam}/ ({len(files)} files in the offline copy, version {version}).")
    rest = [e for e in ["technician", "general", "extra"] if e not in WEB_EXAMS]
    soon = f'<div class="soon small mute">Coming later: {" and ".join(e.capitalize() for e in rest)}.</div>' if rest else ""
    write(os.path.join(WEB, "index.html"), HUB % {"bg": BG, "first": WEB_EXAMS[0], "cards": "\n".join(cards), "soon": soon})
    # host settings (Cloudflare Pages reads _headers): always check for a new service worker and app page
    write(os.path.join(WEB, "_headers"), "/*/sw.js\n  Cache-Control: no-cache\n/*/manifest.webmanifest\n  Cache-Control: no-cache\n")
    print("Built web/index.html. Commit web/ so the site updates.")


if __name__ == "__main__":
    if sys.argv[1:] != ["build"]:
        sys.exit(__doc__)
    build()
